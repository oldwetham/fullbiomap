"""Step 08: tissue media. Human Protein Atlas histology per organ, and HRA 2D functional tissue unit
(FTU) illustrations. (Step 8 was free since Phase 1 removed Wikipedia text.)

Usage: python3 -I pipeline/08-histology.py

Histology (HPA 25.1, CC BY 4.0): for each organ in pipeline/maps/tissue-media.json, take HPA's genes
enriched in that tissue (highest expression first; widening to group-enriched, then tissue-enhanced if
needed) and use the first whose immunohistochemistry is reliable (enhanced or supported), shows high
or medium expression there, and has HPA's representative ("selected") image for that tissue. The
image shows that protein in brown (DAB) and cell nuclei in blue (hematoxylin). Its gene, Ensembl id
and UniProt accessions are recorded so Phase 5 can link the image to the protein's 3D structure.

FTUs (HRA v2.5, CC BY 4.0): every illustration fetched by step 04, attached to the organ whose Uberon
id its crosswalk names, with the cell types it draws and where: `hits` lists, per Cell Ontology id, the
SVG element ids (exactly as written in the file) that draw that cell type, so the viewer can make them
clickable. An SVG with a script, event handler, foreign object or javascript: link is not published.

Outputs: public/ftu/<name>.svg, graph/media.json, reports/histology.md. Each histology image stays in data/raw/hpa/;
step 10 (figures) serves it from public/figures/ with the organ's other figures.
"""
import csv
import json
import re
import shutil
import sys
import urllib.parse
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _http import get_file, get_json  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MAP = json.loads((ROOT / 'pipeline/maps/tissue-media.json').read_text())
HPA = MAP['hpa']
RELEASE = json.loads((ROOT / 'pipeline/maps/hra-release.json').read_text())
API = 'https://www.proteinatlas.org/api/search_download.php'
CATEGORIES = ['Tissue enriched', 'Group enriched', 'Tissue enhanced']
GOOD_RELIABILITY = {'enhanced', 'supported'}
GOOD_LEVEL = {'high', 'medium'}
MAX_PER_CATEGORY = 15  # candidates tried per category, highest expression first
slug = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')
# HPA numbers some IHC tissues ('Stomach 1', 'Stomach 2', 'Skin 1', 'Endometrium 1'); match them all.
same_tissue = lambda name, tissue: re.sub(r'\s+\d+$', '', (name or '').strip().lower()) == tissue


def candidates(tissue, rna):
    for category in CATEGORIES:
        query = urllib.parse.quote(f'tissue_category_rna:{rna};{category}')
        rows = get_json(f'{API}?search={query}&format=json&columns=g,gd,eg,up,rnatsm,relih&compress=no') or []
        # Only genes whose IHC is reliable can qualify; checking that here saves downloading their full records.
        rows = [r for r in rows if (r.get('Reliability (IH)') or '').lower() in GOOD_RELIABILITY]
        def ntpm(r):
            v = (r.get('RNA tissue specific nTPM') or {}).get(rna)
            try:
                return float(v)
            except (TypeError, ValueError):
                return 0.0
        for r in sorted(rows, key=lambda r: (-ntpm(r), r['Gene']))[:MAX_PER_CATEGORY]:
            yield category, r


def pick(tissue, rna):
    for category, r in candidates(tissue, rna):
        try:
            xml = get_file(f'https://www.proteinatlas.org/{r["Ensembl"]}.xml', ROOT / f'data/raw/hpa/{HPA["release"]}/{r["Ensembl"]}.xml', retries=6)
        except Exception as e:  # a record that will not download is skipped, not fatal
            print(f'  skipped {r["Gene"]} ({tissue}): {type(e).__name__}', flush=True)
            continue
        entry = ET.parse(xml).getroot().find('entry')
        ihc = entry.find("tissueExpression[@technology='IHC'][@assayType='tissue']")
        if ihc is None or (ihc.findtext('verification') or '').lower() not in GOOD_RELIABILITY:
            continue
        level = next((d.findtext("level[@type='expression']") for d in ihc.findall('data') if same_tissue(d.findtext('tissue'), tissue) and (d.findtext("level[@type='expression']") or '').lower() in GOOD_LEVEL), None)
        image = next((i for i in ihc.findall("image[@imageType='selected']") if same_tissue(i.findtext('tissue'), tissue)), None)
        if (level or '').lower() not in GOOD_LEVEL or image is None:
            continue
        yield {'category': category, 'gene': r['Gene'], 'description': r.get('Gene description') or r['Gene'], 'ensembl': r['Ensembl'],
                'uniprot': r.get('Uniprot') or [], 'reliability': ihc.findtext('verification').lower(), 'level': level.lower(),
                'imageUrl': image.findtext('imageUrl'), 'tissueUberon': image.find('tissue').get('ontologyTerms')}


media, report = {}, ['# Tissue media', '', f'Generated by `pipeline/08-histology.py`. Human Protein Atlas {HPA["release"]} ({HPA["license"]}); HRA {RELEASE["release"]} 2D FTUs (CC BY 4.0).', '',
                     '| Organ | HPA tissue | Protein (gene) | Selected as | Reliability, level |', '| --- | --- | --- | --- | --- |']
for organ, cfg in MAP['organs'].items():
    if not cfg.get('hpa') or not cfg['nodes']:
        continue
    tissue = cfg['hpa']
    name, choice = f'{slug(organ)}.jpg', None
    for candidate in pick(tissue, cfg.get('hpaRna', tissue)):  # the first candidate whose image actually downloads
        try:
            get_file(candidate['imageUrl'], ROOT / f'data/raw/hpa/{HPA["release"]}/images/{name}', retries=4)
            choice = candidate
            break
        except Exception as e:
            print(f'  skipped {candidate["gene"]} image ({tissue}): {type(e).__name__}', flush=True)
    if not choice:
        report.append(f'| {organ} | {tissue} | none found | | |')
        continue
    protein = choice['description'][:1].lower() + choice['description'][1:] if choice['description'][:2].isupper() is False else choice['description']
    page = f'https://www.proteinatlas.org/{choice["ensembl"]}-{choice["gene"]}/tissue/{urllib.parse.quote(tissue)}'
    record = {
        'kind': 'histology', 'file': f'data/raw/hpa/{HPA["release"]}/images/{name}', 'organ': organ, 'tissue': tissue,
        'caption': f'{tissue[:1].upper() + tissue[1:]} tissue stained for {protein} ({choice["gene"]}). Brown: {choice["gene"]} protein. Blue: cell nuclei (hematoxylin counterstain).',
        'alt': f'Microscope image of {tissue} tissue with {choice["gene"]} protein stained brown and cell nuclei stained blue.',
        'gene': {'symbol': choice['gene'], 'name': choice['description'], 'ensembl': choice['ensembl'], 'uniprot': choice['uniprot']},
        'imageUrl': choice['imageUrl'], 'pageUrl': page, 'stain': 'immunohistochemistry (DAB, brown) with hematoxylin counterstain (blue)',
        'selection': f'HPA {choice["category"].lower()} gene for {tissue}; IHC reliability {choice["reliability"]}, {choice["level"]} expression',
        'license': HPA['license'], 'licenseUrl': HPA['licenseUrl'],
        'attribution': f'Image from the Human Protein Atlas {HPA["release"]} (proteinatlas.org): {choice["gene"]} immunohistochemistry in {tissue}, {choice["imageUrl"]}. {HPA["license"]}.',
    }
    for node in cfg['nodes']:
        media.setdefault(node, []).append(record)
    report.append(f'| {organ} | {tissue} | {choice["description"]} ({choice["gene"]}) | {choice["category"]} | {choice["reliability"]}, {choice["level"]} |')
shutil.rmtree(ROOT / 'public/histology', ignore_errors=True)  # superseded by public/figures/ (step 10)

# HRA 2D FTU illustrations.
RISKY = re.compile(rb'<script|<foreignObject|\son[a-z]+\s*=|javascript:', re.I)
# Crosswalk ids name SVG elements, but Illustrator escapes characters in ids (_x5F_ is '_') and case varies.
unescape = lambda i: re.sub(r'_x([0-9A-Fa-f]{2})_', lambda m: chr(int(m.group(1), 16)), i or '').lower()


def cell_hits(svg_file, rows):
    """Per Cell Ontology id: its label and the SVG element ids that draw it. A crosswalk group (node_group)
    is used whole when all its cells are one cell type; drawn cells outside their group are added singly."""
    raw = svg_file.read_bytes()
    if RISKY.search(raw):
        raise SystemExit(f'{svg_file.name}: has a script, event handler, foreign object or javascript: link; not publishing it')
    tree = ET.fromstring(raw)
    parent = {c: p for p in tree.iter() for c in p}
    ids = {}
    for e in tree.iter():
        if e.get('id'):
            ids.setdefault(unescape(e.get('id')), e)
    def within(e, group):
        while e is not None and e is not group:
            e = parent.get(e)
        return e is group
    cell_rows = [r for r in rows if re.fullmatch(r'CL:\d+', r.get('node_mapped_to') or '')]
    types_in = defaultdict(set)
    for r in cell_rows:
        types_in[unescape(r['node_group'])].add(r['node_mapped_to'])
    hits = defaultdict(lambda: {'label': '', 'ids': set()})
    for r in cell_rows:
        cl, group, node = r['node_mapped_to'], ids.get(unescape(r['node_group'])), ids.get(unescape(r['node_id']))
        h = hits[cl]
        h['label'] = h['label'] or r['node_label']
        if group is not None and types_in[unescape(r['node_group'])] == {cl} and (node is None or within(node, group)):
            h['ids'].add(group.get('id'))
        elif node is not None:
            h['ids'].add(node.get('id'))
    return [{'cl': cl, 'label': h['label'], 'ids': sorted(h['ids'])} for cl, h in sorted(hits.items()) if h['ids']]


by_uberon = {cfg['uberon']: cfg['nodes'] for cfg in MAP['organs'].values() if cfg.get('uberon')}
ftu_dir = ROOT / 'public/ftu'
ftu_dir.mkdir(parents=True, exist_ok=True)
report += ['', '| FTU illustration | Organ | Cell types drawn |', '| --- | --- | --- |']
kept = set()
for name, info in sorted(RELEASE['ftus'].items()):
    svg = next((f for f in info['files'] if f.endswith('.svg')), None)
    if not svg:
        continue
    src = ROOT / 'data/raw/hra' / RELEASE['release'] / '2d-ftu' / name
    with open(src / 'crosswalk.csv', encoding='utf-8', newline='') as fh:
        rows = list(csv.DictReader(fh))
    organs = {r['organ_mapped_to'] for r in rows if r.get('organ_mapped_to')}
    nodes = sorted({n for o in organs for n in by_uberon.get(o, [])})
    cells = sorted({r['node_mapped_to'] for r in rows if re.fullmatch(r'CL:\d+', r.get('node_mapped_to') or '')})
    tissue_label = next((r['tissue_label'] for r in rows if r.get('tissue_label')), name)
    if not nodes:
        report.append(f'| {name} | not shown ({", ".join(sorted(organs))}) | {len(cells)} |')
        continue
    hits = cell_hits(src / svg, rows)
    shutil.copyfile(src / svg, ftu_dir / f'{name}.svg')
    kept.add(f'{name}.svg')
    record = {'kind': 'ftu', 'url': f'/ftu/{name}.svg', 'name': name, 'label': tissue_label[:1].upper() + tissue_label[1:], 'cells': cells, 'hits': hits,
              'caption': f'Functional tissue unit: {tissue_label}. An illustration of the smallest repeating unit of this tissue and the cell types in it.',
              'alt': f'Illustration of the {tissue_label} and its cell types.',
              'doi': info['doi'], 'license': 'CC BY 4.0', 'licenseUrl': 'https://creativecommons.org/licenses/by/4.0/',
              'attribution': f'{info["citation"]} HuBMAP Human Reference Atlas {RELEASE["release"]}, CC BY 4.0.'}
    for node in nodes:
        media.setdefault(node, []).append(record)
    report.append(f'| {name} | {", ".join(nodes)} | {len(cells)} ({len(hits)} clickable) |')
for stale in ftu_dir.glob('*.svg'):
    if stale.name not in kept:
        stale.unlink()

(ROOT / 'graph/media.json').write_text(json.dumps(dict(sorted(media.items())), indent=1, ensure_ascii=False) + '\n')
(ROOT / 'reports/histology.md').write_text('\n'.join(report) + '\n')
print('\n'.join(report))
